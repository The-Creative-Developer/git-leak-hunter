/**
 * Renders docs/BENCHMARK.md from bench/results/*.json. Every number in the document comes from
 * those files, which the benchmark scripts write when they actually run.
 *
 *   npx tsx bench/report.ts
 */
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import type { AccuracyResults, ToolResult } from './accuracy.js';
import type { BenchEnv } from './env.js';
import type { MemoRow } from './memoization.js';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const read = async <T>(f: string): Promise<T> =>
  JSON.parse(await readFile(path.join(ROOT, 'bench', 'results', f), 'utf8')) as T;

interface MemoResults {
  generatedAt: string;
  env: BenchEnv;
  runs: number;
  shape: { paths: number; filesPerCommit: number; secretEvery: number; seed: number };
  profiles: Array<{ name: string; poolSize: number; description: string }>;
  rows: MemoRow[];
}

const pct = (x: number | null | undefined): string =>
  x === null || x === undefined ? '—' : `${(100 * x).toFixed(1)}%`;
const n = (x: number): string => x.toLocaleString('en-US');

function envBlock(e: BenchEnv): string {
  return [
    `- Ran at: ${e.ranAt}`,
    `- Machine: ${e.os}, ${e.cpu} (${e.cores} cores), ${e.memoryGiB} GiB RAM`,
    `- Node ${e.node}; ${e.git}; git-leak-hunter commit \`${e.gitLeakHunterCommit}\``,
  ].join('\n');
}

function toolRow(t: ToolResult): string {
  if (t.status !== 'ran' || !t.totals) {
    const why = t.status === 'not run' ? 'not run (not installed)' : `failed: ${t.error ?? ''}`;
    return `| ${t.tool} | ${t.version ?? '—'} | ${why} | — | — | — | — | — | — |`;
  }
  const x = t.totals;
  return `| ${t.tool} | ${t.version} | ${x.planted} | ${x.tp} | ${x.fp} | ${x.fn} | ${pct(x.precision)} | ${pct(x.recall)} | ${x.rawFindings} |`;
}

async function main(): Promise<void> {
  const acc = await read<AccuracyResults>('accuracy.json');
  const memo = await read<MemoResults>('memoization.json');
  const ran = acc.tools.filter((t) => t.status === 'ran');
  const repos = ran[0]?.repos?.map((r) => r.repo) ?? [];

  const L: string[] = [];
  L.push('# Benchmarks', '');
  L.push(
    '> Generated by `npx tsx bench/report.ts` from `bench/results/*.json`. Every number below was measured by the',
    '> scripts named in each section; nothing is estimated or rounded into a claim. Re-run them to reproduce.',
    '',
  );

  // ---------------------------------------------------------------- accuracy
  L.push('## 1. Accuracy vs Gitleaks and TruffleHog', '');
  L.push('Command: `npx tsx bench/accuracy.ts` → `bench/results/accuracy.json`', '');
  L.push(envBlock(acc.env), '');
  L.push(
    `Corpus: the eight fixture repositories built by \`test/fixtures/buildRepos.ts\` (seed ${acc.seed}). They contain ${ran[0]?.totals?.planted ?? '—'} planted fabricated secrets and the false-positive bait listed in \`ground-truth.json\`. Each tool ran once per repository with its **default rules**, in a non-network mode, without live verification.`,
    '',
    `Matching: ${acc.matching}`,
    '',
  );
  L.push('| Tool | Version | Planted | TP | FP | FN | Precision | Recall | Raw reports |');
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const t of acc.tools) L.push(toolRow(t));
  L.push('');
  L.push('Exact commands (`<repo>` is each fixture directory):', '');
  for (const t of acc.tools) L.push(`- **${t.tool}**: \`${t.command}\``);
  L.push('');

  if (ran.length > 0) {
    L.push('### Per repository (TP / FP / FN)', '');
    L.push(`| Repository | ${ran.map((t) => t.tool).join(' | ')} |`);
    L.push(`| --- | ${ran.map(() => '---').join(' | ')} |`);
    for (const name of repos) {
      const cells = ran.map((t) => {
        const r = t.repos?.find((x) => x.repo === name);
        return r ? `${r.tp} / ${r.fp} / ${r.fn}` : '—';
      });
      L.push(`| \`${name}\` | ${cells.join(' | ')} |`);
    }
    L.push('');
    L.push('### Misses and false positives, by tool', '');
    for (const t of ran) {
      const misses = (t.repos ?? []).flatMap((r) => r.fnIds.map((id) => `\`${r.repo}\`: ${id}`));
      const fps = (t.repos ?? []).flatMap((r) =>
        r.fpLocations.map(
          (f) =>
            `\`${r.repo}\`: \`${f.path}:${f.line}\` (${f.rules.join(', ')})${f.onBait ? ' — on a bait line' : ''}`,
        ),
      );
      L.push(`**${t.tool}**`, '');
      L.push(misses.length ? `- False negatives: ${misses.join('; ')}` : '- False negatives: none');
      L.push(fps.length ? `- False positives: ${fps.join('; ')}` : '- False positives: none');
      L.push('');
    }
  }
  const notRun = acc.tools.filter((t) => t.status !== 'ran');
  if (notRun.length > 0) {
    L.push(
      `Tools marked "not run" were not installed on the benchmark machine. Install them (${notRun.map((t) => `\`${t.install ?? t.tool}\``).join('; ')}) and re-run \`npx tsx bench/accuracy.ts\`, then \`npx tsx bench/report.ts\`. The TruffleHog adapter in \`bench/accuracy.ts\` parses TruffleHog v3 \`--json\` output. It has not been exercised on this machine.`,
      '',
    );
  }

  L.push('### Limitations of this comparison', '');
  L.push(
    '- **Home-field advantage.** The fixtures were written by the same team, alongside Git Leak Hunter. Its thresholds were tuned against them (see `docs/RULES.md`, "Tuning changes"). A perfect score here shows that the rules do what they were designed to do, **not** real-world accuracy.',
    '- **Small, synthetic corpus.** The fixtures hold a few dozen planted secrets with fabricated values. Real repositories have far more varied formats, much more ordinary code, and a different base rate.',
    '- **Location-based matching.** A tool that reports a secret on a different line than the one planted, e.g. a multi-line match anchored elsewhere, counts as a miss plus a false positive.',
    '- **Default configurations only.** No competitor was tuned. Custom rules would change their numbers.',
    '- **Category coverage differs by design.** Some planted categories (Dockerfile `ARG`/`ENV` literals, CI variables) are scanned structurally by Git Leak Hunter. Other tools may not target them by default.',
    '',
  );

  // ---------------------------------------------------------------- memoization
  L.push('## 2. Blob memoization: history scan with cache on vs `--no-cache`', '');
  L.push(
    `Command: \`npx tsx bench/memoization.ts ${memo.runs}\` → \`bench/results/memoization.{json,csv}\``,
    '',
  );
  L.push(envBlock(memo.env), '');
  L.push(
    `Repositories: synthetic, generated with \`git fast-import\` by \`test/fixtures/synthRepo.ts\`. Each has ${memo.shape.paths} paths and ${memo.shape.filesPerCommit} files rewritten per commit; every ${memo.shape.secretEvery}th file content carries a fabricated token (seed ${memo.shape.seed}).`,
  );
  for (const p of memo.profiles)
    L.push(`- **${p.name}**: ${p.description} (pool size ${n(p.poolSize)}).`);
  L.push('');
  L.push(
    `Each configuration: one unrecorded warm-up, then ${memo.runs} measured runs alternating cache / no-cache. Time = the engine's measured \`stats.durationMs\` (git walk + blob reads + detection; report writing excluded). The scans run in-process.`,
    '',
    '"Snapshot file versions" is what a scanner that checks out every commit and reads every file would read. It is measured as the sum of `git ls-tree -r` entries over all commits. "File versions seen" is what Git Leak Hunter reads from the changed-files walk. "Unique blobs scanned" is what detection actually ran on.',
    '',
  );
  L.push(
    '| Profile | Commits | Snapshot file versions | File versions seen | Unique blobs scanned | Cache hits | Cache: median / min (ms) | No cache: median / min (ms) | Ratio of medians |',
  );
  L.push('| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
  const keys = [...new Set(memo.rows.map((r) => `${r.profile}|${r.commits}`))];
  for (const k of keys) {
    const [profile, commits] = k.split('|');
    const on = memo.rows.find(
      (r) => r.profile === profile && String(r.commits) === commits && r.mode === 'cache',
    );
    const off = memo.rows.find(
      (r) => r.profile === profile && String(r.commits) === commits && r.mode === 'no-cache',
    );
    if (!on || !off) continue;
    L.push(
      `| ${profile} | ${n(on.commits)} | ${n(on.snapshotFileVersions)} | ${n(on.fileVersionsSeen)} | ${n(on.uniqueBlobsScanned)} | ${n(on.cacheHits)} | ${on.medianMs} / ${on.minMs} | ${off.medianMs} / ${off.minMs} | ${(off.medianMs / on.medianMs).toFixed(2)}× |`,
    );
  }
  L.push('');
  L.push('Raw per-run samples are in `bench/results/memoization.json`.', '');
  L.push('### Reading the numbers', '');
  L.push(
    '- In the high-reuse profile, the number of blobs detection runs on stays constant as history grows, while file versions seen grows linearly. This is the `O(unique blobs)` vs `O(commits × files)` argument from `docs/ARCHITECTURE.md`, shown in measured counters.',
    '- In the low-reuse profile, almost every write is a new blob, so the cache has little to reuse and the two modes take similar time. Memoization pays off in proportion to blob reuse: reverts, copies, branches, generated files. It does nothing for histories where every change is unique.',
    '- Even with `--no-cache`, Git Leak Hunter reads only changed files per commit. The gap to a full-snapshot scan is the "Snapshot file versions" column; that column is a count, not a timing.',
    '- These are single-machine timings of synthetic repositories. They are not a prediction for any particular real repository.',
    '',
  );

  // ---------------------------------------------------------------- entropy
  L.push('## 3. Entropy calibration', '');
  L.push(
    'The measured miss rates of the entropy layer, with and without length normalisation, are in `docs/RULES.md` ("Calibration"). They were generated by `npx tsx bench/entropy-calibration.ts 10000`.',
    '',
  );

  await writeFile(path.join(ROOT, 'docs', 'BENCHMARK.md'), L.join('\n'));
  process.stderr.write('wrote docs/BENCHMARK.md\n');
}

await main();
